export function enumLabel(tool: string | undefined, version: string | undefined, path: string, value: unknown, intl: IntlShape): string | null {
  if (!tool || version !== schemaVersion.sha256 || typeof value !== 'string' || intl.locale.startsWith('en')) return null
  const snapshot = toolSchemaEnums as unknown as { fields: Record<string, string[]>; enums: Record<string, Record<string, string[]>> }
  const fieldPath = path.endsWith('.*') ? path.slice(0, -2) : path
  if (!snapshot.fields?.[tool]?.includes(fieldPath) || !snapshot.enums?.[tool]?.[path]?.includes(value)) return null
  const field = path.split('.').filter((part) => part !== '*').pop()
  const key = `${field}:${value}`
  if (!Object.hasOwn(enumMessages, key)) return null
  const descriptor = enumMessages[key as keyof typeof enumMessages] as MessageDescriptor
  return descriptor.id && Object.hasOwn(intl.messages, descriptor.id) ? intl.formatMessage(descriptor) : null
}
