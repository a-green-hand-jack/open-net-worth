export function fieldLabel(key: string, intl: IntlShape, fallback?: string, tool?: string, version?: string, path = key): string {
  if (intl.locale.startsWith('en')) return fallback || humanizeType(key)
  const snapshot = toolSchemaSnapshot as unknown as { fields: Record<string, string[]> }
  if (!tool || version !== schemaVersion.sha256 || !snapshot.fields?.[tool]?.includes(path)) return fallback || humanizeType(key)
  return Object.hasOwn(fields, key) ? intl.formatMessage(fields[key as keyof typeof fields] as MessageDescriptor) : fallback || humanizeType(key)
}

export function fieldPathLabel(path: string, intl: IntlShape, tool?: string, version?: string): string {
  const parts = path.split('.')
  return parts.map((part, index) => {
    const schemaPath = parts.slice(0, index + 1).map((item) => /^\d+$/.test(item) ? '*' : item).join('.')
    return fieldLabel(part, intl, part, tool, version, schemaPath)
  }).join(' › ')
}

export function displayValue(value: unknown, intl: IntlShape, tool?: string, version?: string, path = ''): string {
  if (intl.locale.startsWith('en')) return plainText(value)
  const translated = enumLabel(tool, version, path, value, intl)
  if (translated !== null) return translated
  if (typeof value === 'boolean') return value ? intl.formatMessage({ id: 'chat.approval.yes', defaultMessage: 'Yes' }) : intl.formatMessage({ id: 'chat.approval.no', defaultMessage: 'No' })
  if (Array.isArray(value)) return value.length ? value.map((item) => displayValue(item, intl, tool, version, path ? `${path}.*` : '*')).join(', ') : intl.formatMessage({ id: 'chat.agent.none', defaultMessage: 'none' })
  if (isRecord(value)) {
    const entries = Object.entries(value)
    return entries.length ? entries.map(([key, item]) => {
      const childPath = path ? `${path}.${key}` : key
      const childTool = /[.*]/.test(key) ? undefined : tool
      return `${fieldLabel(key, intl, key.replace(/_/g, ' '), childTool, version, childPath)}: ${displayValue(item, intl, childTool, version, childPath)}`
    }).join(', ') : intl.formatMessage({ id: 'chat.agent.none', defaultMessage: 'none' })
  }
  return value == null || value === '' ? '—' : String(value)
}
